/// The stand's enrolment: the pinned prototype, the shipped thresholds and a calibration
/// with no negatives — everything a listening session reads before its first window. The
/// prototype must be as wide as the pair's embedding, or every cosine would score against
/// part of a vector, so a pair of another width is refused here rather than at the
/// printed witness.
pub(crate) fn stand(pair: &loader::Pair) -> Result<wake::Enrollment> {
    let width = pair.body.config().d;
    if PROTOTYPE.len() != width {
        bail!(
            "the pinned prototype is {} wide — the pair answers {width}-wide embeddings",
            PROTOTYPE.len()
        );
    }
    Ok(wake::Enrollment {
        phrase: "stand".to_string(),
        prototype: PROTOTYPE.to_vec(),
        utterance_count: UTTERANCES,
        calibration: wake::Calibration::default(),
        negative_prototypes: Vec::new(),
        thresholds: wake::Thresholds::DEFAULT,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Arc;

    use crate::host;
    use crate::listen::{self, Listener};
    use crate::loader::{Pair, Role};
    use crate::reference;

    /// The prototype from the pinned clip, through the ear's own one-window front end.
    fn derive(listener: &mut Listener) -> Vec<f32> {
        let path = crate::corpus::pinned(reference::LISTEN_CLIP)
            .expect("the pinned corpus recording is installed")
            .display()
            .to_string();
        let mut detector = earshot::Detector::default();
        let mut utterances = Vec::new();
        for index in 0..UTTERANCES {
            let at = index * listen::SCORE_STRIDE_SAMPLES;
            let window = host::wav_mono_16k(&path, at, listen::WINDOW_SAMPLES)
                .expect("a window of the pinned corpus recording");
            if !crate::vad::speech_mask(&window, &mut detector)
                .iter()
                .any(|speech| *speech)
            {
                continue;
            }
            utterances.push(listener.embed(&window).expect("the window embeds"));
        }
        assert!(
            utterances.len() >= wake::MIN_ENROLLMENT_UTTERANCES,
            "{} of {UTTERANCES} windows gated speech — too few to centre a prototype",
            utterances.len()
        );
        wake::normalized_centroid(&utterances).expect("one width")
    }

    /// The pin is the derivation, not a vector somebody typed: the same clip through the
    /// same model must still centre on it, or the rows are scoring against a stale voice.
    ///
    /// `#[ignore]`d: it needs the ASR pair and the pinned corpus recording. Run with
    /// `cargo test -p mahbot-inference --release --lib the_pin_is_the_derivation --
    /// --ignored --nocapture`.
    #[test]
    #[ignore = "needs the ASR pair and the pinned recording"]
    fn the_pin_is_the_derivation() {
        if rlx_ir::env::skip_unless_device("wgpu", true, rlx_wgpu::is_available()) {
            return;
        }
        crate::device::pin_gpu();
        if crate::corpus::dir().is_err() {
            eprintln!("skipped: the pinned corpus is not installed");
            return;
        }
        let pair = match Pair::of_role(Role::Recognition) {
            Ok(pair) => Arc::new(pair),
            Err(error) => {
                eprintln!("skipped: {error:#}");
                return;
            }
        };
        let derived = derive(&mut Listener::new(pair));
        let similarity = wake::cosine(&derived, &PROTOTYPE);
        assert!(
            similarity > 0.999,
            "the prototype moved from its derivation (cosine {similarity:.6})"
        );
    }
}
