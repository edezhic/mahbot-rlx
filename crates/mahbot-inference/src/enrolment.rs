//! The stand's pinned wake enrolment: the one-time setup the listening rows do not price.
//!
//! The product enrols a voice saying the wake phrase, calibrates the floor against a
//! negative pool and stores the prototype; a listening session loads it and never derives
//! it. The rows need the same object before their first window, and deriving it would read
//! the models the cold column exists to price, so it is pinned here — the way
//! [`crate::speaker::SPEAKER_EMBED`] pins a voice.
//!
//! The derivation, once, and the test that keeps it: [`crate::reference::LISTEN_CLIP`]'s
//! first [`UTTERANCES`] scoring strides, each window VAD-gated and embedded through
//! [`crate::listen::Listener::embed`], the windows that gate no speech skipped rather than
//! averaged, and the L2-normalised centroid of the rest. `the_pin_is_the_derivation`
//! (hand-run, `#[ignore]`d) is that derivation: it rebuilds the centroid from the clip
//! through the ear's own front end and holds the pin to it at cosine > 0.999. The voice is
//! not the enrolled one and the words are not the wake phrase: the rows price the
//! decision's cost, which is the same arithmetic whatever the prototype holds, and the
//! corpus is the material they already read.
//!
//! The calibration is the shipped default — an enrolment with no usable negatives — so the
//! floor is [`wake::DEFAULT_SOFT_FLOOR`] and the bar is three times the fire factor: the
//! active row's speech never reaches it, which is what makes that row "speech that does
//! not fire". The anti-prototypes are not pinned: this prototype is a different speaker from
//! the row's audio, so the decision takes the same branch with or without them, and
//! `docs/records.md` states what the empty branch costs.

